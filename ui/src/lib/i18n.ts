export type TKey = keyof typeof ENTRIES;
export type Lang = "de" | "en";

export const DICTS: Record<Lang, Record<TKey, string>> = {
  de: Object.fromEntries(Object.entries(ENTRIES).map(([k, v]) => [k, v[0]])) as Record<TKey, string>,
  en: Object.fromEntries(Object.entries(ENTRIES).map(([k, v]) => [k, v[1]])) as Record<TKey, string>,
};

let lang: Lang = "de";
let version = 0;
const listeners = new Set<() => void>();

export const currentLang = () => lang;

/** Switches the language (and re-renders every component using `useT`). */
export function setLang(l: Lang) {
  const next: Lang = l === "en" ? "en" : "de";
  document.documentElement.lang = next;
  if (next === lang) return;
  lang = next;
  refreshI18n();
}

/** Re-renders `useT` components (language or shortcut hints changed). */
export function refreshI18n() {
  version++;
  listeners.forEach((f) => f());
}

export function translate(l: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = DICTS[l][key] ?? DICTS.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Translation in the current language (outside React, or in memoized rows). */
export const t = (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);

const subscribe = (f: () => void) => {
  listeners.add(f);
  return () => {
    listeners.delete(f);
  };
};

/** `t` for components: re-renders when the language or the shortcut hints change. */
export function useT() {
  useSyncExternalStore(subscribe, () => version);
  return t;
}
